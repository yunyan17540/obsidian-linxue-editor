export function modeInstruction(mode: ReviewMode): string {
  if (mode === "chatty") {
    return `本次采用「话痨」口吻。你可以先用两三句像老朋友见面那样闲聊或轻吐槽，再进入编辑意见，允许偶尔跑半句再拉回来。点评要说全：你的理解、真正成立的亮点、致命问题、重要问题、可优化细节、可执行改法、若有分叉就口头比较利弊，以及下一步最优先的任务。内容具体，落到原文的句子、人物或情节上。篇幅可以长，但每一段都要有信息，不要空转夸奖。`;
  }
  if (mode === "quiet") {
    return `本次采用「淑女安静」口吻。话少、柔和、不抢话，像坐在旁边低声说。用一两句说明你理解的内容，再用很短的一句点出真正有效的地方。不足只说最致命或最重要的一两处，并给一条可以马上动手的改法。不要铺三类问题，不要列方案菜单，不要闲聊。若与上面的完整结构要求冲突，以这段的篇幅要求为准，但判断标准不变：具体、坦率、不空泛。全文控制在大约一百二十到两百个字，方便一段语音说完。`;
  }
  return `本次采用「中庸」口吻。不啰嗦，也不过分省话。按这个口头顺序说完即可：你的理解、一处真正成立的亮点、最要紧的不足（致命优先，其次重要问题，细节只在确实值得提时带一句）、一条或两条可执行改法、下一步最优先的任务。有两种明显不同的改法时，用两三句比较利弊。批评要落到具体原文。篇幅大约四百到七百字，适合一口气听完。`;
}

export function temperatureFor(mode: ReviewMode, override: number): number {
  if (override > 0) return override;
  if (mode === "chatty") return 0.9;
  if (mode === "quiet") return 0.45;
  return 0.7;
}
