export function continueInstruction(mode: ReviewMode): string {
  const length = mode === "chatty"
    ? "大约续写一百五十到三百字。"
    : mode === "quiet"
      ? "大约续写四十到九十个字，点到为止。"
      : "大约续写八十到一百六十个字。";
  return `这次不是点评，而是替我顺着已有文字往下写一段。只输出可以紧接在原文后面的正文，不要解释，不要标题，不要引号包裹，不要 Markdown。顺着我的人称、语气、情节和个人风格写，不要另起新章节，不要替我收束整章，不要重复我刚刚写过的句子。${length}`;
}

